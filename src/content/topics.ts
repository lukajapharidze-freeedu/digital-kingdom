// ---------- დამხმარე ფუნქციები ----------

export function topicsForGrade(grade: Grade): Topic[] {
  return TOPICS.filter(topic => topic.grades.includes(grade))
}

/** პოულობს თემას კოდით (რეგისტრს და ზედმეტ ცარიელს არ აქვს მნიშვნელობა) */
export function findTopicByCode(code: string): Topic | undefined {
  const trimmed = code.trim()
  if (!trimmed) return undefined
  const hash = hashTopicCode(trimmed)
  return TOPICS.find(topic => topic.codeHash === hash)
}

export function roundQuestions(topic: Topic, round: 1 | 2): TopicQuestion[] {
  return topic.questions.filter(question => question.round === round)
}

// ---------- პასუხის შემოწმება ----------

function normalize(value: string): string {
  return value
    .trim()
    .toLocaleLowerCase()
    .replace(/[.,!?;:"“”„'`()«»\-–—]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

// ზედმეტი სიტყვები, რომლებიც პასუხს არ ცვლის ("ლოგიკური შეცდომაა" = "ლოგიკური")
const FILLER = new Set(['შეცდომა', 'შეცდომაა', 'არის', 'ეს', 'ესაა', 'ჰქვია', 'და'])

export function isAnswerCorrect(question: TopicQuestion, input: string): boolean {
  const answer = normalize(input)
  if (!answer) return false

  const expected = question.answers.map(normalize)
  if (expected.includes(answer)) return true

  const stripped = answer
    .split(' ')
    .filter(word => word && !FILLER.has(word))
    .join(' ')
  return stripped.length > 0 && expected.includes(stripped)
}

// ---------- თამაშებისთვის (მაგ. CPU Dash) ----------

export interface GameQuestion {
  prompt: string
  answers: string[]
  /** მინიშნება პასუხის შეცდომისას */
  hint: string
  /** აკადემიის იგივე წესით შემოწმება (ზედმეტი სიტყვები, წერტილები და სხვ.) */
  check: (input: string) => boolean
}

/**
 * თამაშის კითხვები = აკადემიის იგივე კითხვები.
 * თუ ბავშვმა თემა უკვე გახსნა — იმ თემის კითხვებს იღებს;
 * თუ ბიბლიოთეკა გამოტოვა — მაინც ამ კლასის თემის კითხვებს ეკითხებიან და პასუხი თვითონ უნდა მოძებნოს.
 */
export function questionsForGame(
  grade: Grade,
  openedTopicIds: string[],
  isSolved: (topicId: string, questionId: string) => boolean = () => false,
): GameQuestion[] {
  const forGrade = topicsForGrade(grade)
  const opened = forGrade.filter(topic => openedTopicIds.includes(topic.id))
  const topics = opened.length > 0 ? opened : forGrade

  return topics.flatMap(topic => {
    const round1 = roundQuestions(topic, 1)
    // მეორე წრის კითხვები მხოლოდ მაშინ, როცა ბავშვმა პირველი წრე დაასრულა
    // (მხოლოდ მაშინ იხსნება დამატებითი ტექსტი, ამიტომ "არ გვისწავლიაო" არ გამოვა)
    const round1Done = round1.length > 0 && round1.every(q => isSolved(topic.id, q.id))
    const pool = round1Done ? topic.questions : round1

    return pool.map(question => ({
      prompt: question.prompt,
      answers: question.answers,
      hint: `მინიშნება: პასუხი ბიბლიოთეკაში, ${
        question.round === 1 ? 'ძირითადი' : 'დამატებითი'
      } ტექსტის ${question.page}-ე გვერდზეა.`,
      check: (input: string) => isAnswerCorrect(question, input),
    }))
  })
}